# ---- Drawing helpers ------------------------------------------------------------------------
def flake(cx, cy, r, opacity=1.0, rot=0.0, width=None):
    """A six-armed snowflake as SVG lines."""
    sw = width or max(2.0, r * 0.09)
    arms = "".join(
        f'<g transform="rotate({rot + k * 60:.1f} {cx:.1f} {cy:.1f})">'
        f'<line x1="{cx:.1f}" y1="{cy:.1f}" x2="{cx:.1f}" y2="{cy - r:.1f}"/>'
        f'<polyline points="{cx - r * .3:.1f},{cy - r * .75:.1f} {cx:.1f},{cy - r * .5:.1f} {cx + r * .3:.1f},{cy - r * .75:.1f}"/>'
        f'<polyline points="{cx - r * .17:.1f},{cy - r * .97:.1f} {cx:.1f},{cy - r * .82:.1f} {cx + r * .17:.1f},{cy - r * .97:.1f}"/>'
        "</g>" for k in range(6))
    return (f'<g fill="none" stroke="#fff" stroke-opacity="{opacity:.2f}" stroke-width="{sw:.1f}" '
            f'stroke-linecap="round" stroke-linejoin="round">{arms}</g>')

def flakes(w, h, n, seed, rmin=14, rmax=64):
    """Scatter n faint snowflakes over a w x h area, without overlaps (fixed seed: same result every run)."""
    rnd, placed, tries = random.Random(seed), [], 0
    while len(placed) < n and tries < 5000:
        tries += 1
        r = rnd.uniform(rmin, rmax)
        x, y = rnd.uniform(-r * .3, w + r * .3), rnd.uniform(-r * .3, h + r * .3)
        if all((x - px) ** 2 + (y - py) ** 2 > (r + pr + 30) ** 2 for px, py, pr in placed):
            placed.append((x, y, r))
    body = "".join(flake(x, y, r, opacity=.1 + .16 * rnd.random(), rot=rnd.uniform(0, 60)) for x, y, r in placed)
    return f'<svg class="layer" viewBox="0 0 {w} {h}" preserveAspectRatio="none">{body}</svg>'

def icon_flake(size, color="#fff"):
    return (f'<svg width="{size}" height="{size}" viewBox="-12 -12 24 24" style="display:inline-block;vertical-align:middle">'
            f'{flake(0, 0, 10.5, width=2.2).replace("#fff", color)}</svg>')

def snow(w, h):
    """Snowy ground: a soft back drift and a white front drift."""
    return f"""<svg class="layer" style="top:auto;height:{h}px" viewBox="0 0 {w} {h}" preserveAspectRatio="none">
<path d="M0 {h * .16:.0f} C {w * .2:.0f} {h * -.02:.0f}, {w * .38:.0f} {h * .2:.0f}, {w * .56:.0f} {h * .1:.0f} S {w * .86:.0f} {h * -.04:.0f}, {w} {h * .1:.0f} V {h} H 0 Z" fill="#fff" fill-opacity=".35"/>
<path d="M0 {h * .26:.0f} C {w * .16:.0f} {h * .12:.0f}, {w * .34:.0f} {h * .32:.0f}, {w * .52:.0f} {h * .22:.0f} S {w * .84:.0f} {h * .1:.0f}, {w} {h * .24:.0f} V {h} H 0 Z" fill="#fff"/>
</svg>"""

def qr_svg(url, size, color=INK):
    """QR code as crisp SVG, generated by macOS CoreImage (no packages needed)."""
    js = WORK / "qr.js"
    js.write_text("""ObjC.import('CoreImage'); ObjC.import('AppKit');
function run(argv) {
  const f = $.CIFilter.filterWithName('CIQRCodeGenerator');
  f.setValueForKey($(argv[0]).dataUsingEncoding($.NSUTF8StringEncoding), 'inputMessage');
  f.setValueForKey($('M'), 'inputCorrectionLevel');
  const rep = $.NSBitmapImageRep.alloc.initWithCIImage(f.outputImage);
  const rows = [];
  for (let y = 0; y < rep.pixelsHigh; y++) { let r = '';
    for (let x = 0; x < rep.pixelsWide; x++) r += rep.colorAtXY(x, y).brightnessComponent < .5 ? '1' : '0';
    rows.push(r); }
  return rows.join('\\n');
}""")
    rows = subprocess.run(["osascript", "-l", "JavaScript", str(js), url], check=True, capture_output=True, text=True).stdout.split()
    while rows and "1" not in rows[0]: rows.pop(0)
    while rows and "1" not in rows[-1]: rows.pop()
    first = min(r.index("1") for r in rows if "1" in r)
    last = max(r.rindex("1") for r in rows if "1" in r)
    rows = [r[first:last + 1] for r in rows]
    n, q = len(rows), 4  # q = quiet zone in modules
    path = "".join(f"M{x + q} {y + q}h1v1h-1z" for y, r in enumerate(rows) for x, c in enumerate(r) if c == "1")
    return (f'<svg width="{size}" height="{size}" viewBox="0 0 {n + 2 * q} {n + 2 * q}" shape-rendering="crispEdges">'
            f'<rect width="100%" height="100%" fill="#fff"/><path d="{path}" fill="{color}"/></svg>')


